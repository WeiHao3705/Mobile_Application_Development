-- =====================================================================
-- FitTrack: schema for a NEW Supabase project.
--
-- Reverse-engineered from the Dart code in lib/ (repositories, models,
-- storage services). Column types are best guesses; check them against the
-- old project's table editor if you can (see "Things to verify" below).
--
-- How to use: Supabase dashboard -> SQL Editor -> paste this whole file -> Run.
-- It is safe to run more than once.
--
-- Security model (a big improvement over "RLS disabled"):
--   * RLS is ON for every table.
--   * Signed-in users (role `authenticated`) can read/write the app tables.
--     This is still permissive between users. Per-user ownership policies
--     (auth.uid() = auth_user_id) are "Phase 3", once auth_user_id is filled.
--   * Visitors who are not signed in (role `anon`) can only: look up a
--     profile for login, and create a profile at sign-up.
--   * The legacy `password` column cannot be read by the app at all.
--   * Nobody can change `is_admin` from the app. Make admins in the
--     dashboard:  UPDATE "User" SET is_admin = true WHERE username = '...';
--
-- Things to verify against the old project (types are guesses):
--   * Exercise.secondary_muscle is varchar[] (the code says so).
--   * Aerobic_Activity uses the quoted column "caloriesPerKM"; one screen
--     (aerobic_type.dart) reads 'calories_per_km' instead, which looks like
--     an existing bug rather than a second column.
--   * WaterIntake uses quoted camelCase columns, as the code does.
-- =====================================================================

-- ---------- Users ---------------------------------------------------
create table if not exists "User" (
  user_id        bigint generated by default as identity primary key,
  auth_user_id   uuid unique references auth.users (id) on delete set null,
  username       text not null unique,
  full_name      text,
  email          text not null unique,
  password       text,                 -- legacy hash; see Phase 2 of the plan
  gender         text,
  date_of_birth  date,
  height         numeric,
  current_weight numeric,
  target_weight  numeric,
  profile_photo  text,
  is_admin       boolean not null default false,
  created_at     timestamptz not null default now()
);

-- ---------- Nutrition -------------------------------------------------
create table if not exists "Food" (
  food_id           bigint generated by default as identity primary key,
  user_id           bigint not null references "User" (user_id) on delete cascade,
  food_name         text not null,
  category          text not null default 'Other',
  calories_per_100g numeric not null default 0,
  protein_per_100g  numeric not null default 0,
  carbs_per_100g    numeric not null default 0,
  fat_per_100g      numeric not null default 0
);

create table if not exists "MealLog" (
  meal_id        bigint generated by default as identity primary key,
  user_id        bigint not null references "User" (user_id) on delete cascade,
  meal_type      text not null,
  meal_name      text,
  meal_date      timestamptz not null default now(),
  total_calories numeric,
  total_proteins numeric,
  total_carbs    numeric,
  total_fats     numeric,
  image_url      text
);

create table if not exists "MealFood" (
  meal_food_id bigint generated by default as identity primary key,
  meal_id      bigint not null references "MealLog" (meal_id) on delete cascade,
  food_id      bigint not null references "Food" (food_id) on delete cascade,
  quantity     numeric not null,
  unit         text not null default 'g'
);

create table if not exists "DailyGoals" (
  daily_goals_id  bigint generated by default as identity primary key,
  user_id         bigint not null unique references "User" (user_id) on delete cascade,
  target_calories numeric,
  target_protein  numeric,
  target_carbs    numeric,
  target_fat      numeric,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ---------- Body tracking ---------------------------------------------
create table if not exists "WeightLogs" (
  weight_log_id bigint generated by default as identity primary key,
  user_id       bigint not null references "User" (user_id) on delete cascade,
  weight        numeric not null,
  date          date not null
);

create table if not exists "WaterIntake" (
  water_intake_id bigint generated by default as identity primary key,
  user_id         bigint not null references "User" (user_id) on delete cascade,
  "currentAmount" numeric not null default 0,
  "targetAmount"  numeric not null default 0,
  "lastUpdated"   timestamptz not null default now(),
  date            date not null
);

-- ---------- Exercises, plans, records -----------------------------------
-- The exercise library is global data. A new project starts EMPTY; ask your
-- friend to export the Exercise table (CSV) from the old project and import
-- it with Table Editor -> Import data from CSV.
create table if not exists "Exercise" (
  exercise_id      text primary key,
  exercise_name    text not null,
  primary_muscle   text,
  secondary_muscle text[],
  equipment        text,
  instruction      text,
  image            text,
  video            text
);

create table if not exists "Exercise_Plan" (
  plan_id     uuid primary key default gen_random_uuid(),
  user_id     bigint not null references "User" (user_id) on delete cascade,
  plan_name   text not null,
  description text,
  created_at  timestamptz not null default now()
);

create table if not exists "Exercise_Plan_Details" (
  detail_id    uuid primary key default gen_random_uuid(),
  plan_id      uuid not null references "Exercise_Plan" (plan_id) on delete cascade,
  user_id      bigint references "User" (user_id) on delete cascade,
  exercise_id  text not null,
  order_index  int not null default 0,
  sets         int,
  reps         int,
  weight       numeric,
  rest_seconds int,
  notes        text
);

create table if not exists "Exercise_Record" (
  record_id       uuid primary key,   -- generated by the app
  user_id         bigint not null references "User" (user_id) on delete cascade,
  record_title    text,
  record_image    text,
  created_at      timestamptz not null default now(),
  duration        int,
  training_volume numeric,
  num_of_sets     int
);

create table if not exists "Exercise_Record_Details" (
  detail_id     uuid primary key,     -- generated by the app
  record_id     uuid not null references "Exercise_Record" (record_id) on delete cascade,
  exercise_name text,
  order_index   int not null default 0,
  sets          int,
  reps          int,
  weight        numeric,
  notes         text
);

-- ---------- Aerobic -----------------------------------------------------
