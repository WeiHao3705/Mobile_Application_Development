  location        text,
  total_distance  numeric,
  average_pace    int,
  calories_burned int,
  total_step      int,
  elevation_gain  int,
  start_at        timestamptz,
  end_at          timestamptz,
  moving_time     int,
  route_image     text,
  snap_photo      text,
  description     text,
