-- =====================================================================
-- Row Level Security
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array[
    'User','Food','MealLog','MealFood','DailyGoals','WeightLogs','WaterIntake',
    'Exercise','Exercise_Plan','Exercise_Plan_Details','Exercise_Record',
    'Exercise_Record_Details','Aerobic_Activity','AerobicExercise'
  ] loop
    execute format('alter table %I enable row level security', t);
  end loop;
end $$;

-- Signed-in users: full access to the app tables (tightened in Phase 3).
do $$
declare t text;
begin
  foreach t in array array[
    'Food','MealLog','MealFood','DailyGoals','WeightLogs','WaterIntake',
    'Exercise','Exercise_Plan','Exercise_Plan_Details','Exercise_Record',
    'Exercise_Record_Details','Aerobic_Activity','AerobicExercise'
  ] loop
    execute format('drop policy if exists "app_authenticated_all" on %I', t);
    execute format(
      'create policy "app_authenticated_all" on %I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- "User": login needs a pre-login lookup, sign-up needs a pre-login insert.
drop policy if exists "user_select" on "User";
drop policy if exists "user_insert" on "User";
drop policy if exists "user_update" on "User";
create policy "user_select" on "User" for select to anon, authenticated using (true);
create policy "user_insert" on "User" for insert to anon, authenticated with check (true);
create policy "user_update" on "User" for update to authenticated using (true) with check (true);

-- Column-level privileges on "User": the app can never read `password`,
-- and can never change `is_admin` or `auth_user_id`.
revoke all on "User" from anon, authenticated;
grant select (user_id, auth_user_id, username, full_name, email, gender,
              date_of_birth, height, current_weight, target_weight,
              profile_photo, is_admin, created_at)
  on "User" to anon, authenticated;
grant insert (username, full_name, email, password, gender, date_of_birth,
              height, current_weight, target_weight)
  on "User" to anon, authenticated;
grant update (username, full_name, email, password, gender, date_of_birth,
              height, current_weight, target_weight, profile_photo)
  on "User" to authenticated;

-- Plain table privileges for everything else (RLS above still applies).
grant select, insert, update, delete
  on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
-- re-apply the stricter User grants after the blanket grant above
revoke all on "User" from anon, authenticated;
grant select (user_id, auth_user_id, username, full_name, email, gender,
              date_of_birth, height, current_weight, target_weight,
              profile_photo, is_admin, created_at)
  on "User" to anon, authenticated;
grant insert (username, full_name, email, password, gender, date_of_birth,
              height, current_weight, target_weight)
  on "User" to anon, authenticated;
grant update (username, full_name, email, password, gender, date_of_birth,
              height, current_weight, target_weight, profile_photo)
  on "User" to authenticated;

-- =====================================================================
-- Storage buckets (all public-read, matching getPublicUrl() in the app)
-- =====================================================================
insert into storage.buckets (id, name, public) values
  ('Exercise_Image',        'Exercise_Image',        true),
  ('Exercise_Video',        'Exercise_Video',        true),
  ('aerobic_route',         'aerobic_route',         true),
  ('meal_photo',            'meal_photo',            true),
  ('profile_photo',         'profile_photo',         true),
  ('exercise_record_image', 'exercise_record_image', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "app_storage_write"  on storage.objects;
drop policy if exists "app_storage_update" on storage.objects;
drop policy if exists "app_storage_delete" on storage.objects;
create policy "app_storage_write" on storage.objects for insert to authenticated
  with check (bucket_id in ('Exercise_Image','Exercise_Video','aerobic_route',
                            'meal_photo','profile_photo','exercise_record_image'));
create policy "app_storage_update" on storage.objects for update to authenticated
  using (bucket_id in ('Exercise_Image','Exercise_Video','aerobic_route',
                       'meal_photo','profile_photo','exercise_record_image'));
create policy "app_storage_delete" on storage.objects for delete to authenticated
  using (bucket_id in ('Exercise_Image','Exercise_Video','aerobic_route',
                       'meal_photo','profile_photo','exercise_record_image'));
